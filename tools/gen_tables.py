"""Generate app/core/tables.h: every constant the audio path needs, computed here once in double precision and
stored as integers. The core then needs no libm at all, so the FM-1, the browser and the host compute bit-identical
audio (the golden tests rely on it).

    python3 tools/gen_tables.py app/core/tables.h
"""
import math
import sys

SR = 44100
CTL = 32                       # control-rate block (samples): envelopes and filter coefficients step at this rate


def arr(name, ctype, vals, per=12):
    lines = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main(out):
    t = []
    # sine, Q15, 256 points + guard
    sine = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]
    t.append("/* sin over one cycle, Q15, 256 points and a guard point for interpolation */")
    t.append(arr("TAB_SINE", "int16_t", sine, 16))

    # phase increment per sample for MIDI notes 0..127 (+ one guard), 2^32 = one cycle
    inc = [min(0xFFFFFFFF, round(440.0 * 2 ** ((n - 69) / 12) * 2 ** 32 / SR)) for n in range(129)]
    t.append("/* phase increment per sample of MIDI note n (A4 = 440 Hz at 44.1 kHz); 2^32 = one cycle */")
    t.append(arr("TAB_NOTE_INC", "uint32_t", inc, 8))

    # decay: param 0..127 -> time to -60 dB, 2 ms .. 8 s, exponential; coefficient per control block, Q16
    def decay_ms(p):
        return 2.0 * (8000.0 / 2.0) ** (p / 127.0)
    dk = []
    for p in range(128):
        tau = decay_ms(p) / 1000.0 / math.log(1000.0)      # -60 dB time -> time constant
        dk.append(min(65535, round(65536 * math.exp(-CTL / (tau * SR)))))
    t.append("/* exponential decay: param 0..127 = 2 ms .. 8 s to -60 dB; multiplier per 32-sample block, Q16 */")
    t.append(arr("TAB_DECAY_K", "uint16_t", dk, 12))
    t.append("/* the same times in ms, for the screen */")
    t.append(arr("TAB_DECAY_MS", "uint16_t", [round(decay_ms(p)) for p in range(128)], 12))

    # one-pole TPT coefficient G = g / (1 + g), g = tan(pi f / fs), for f = MIDI note 0..127 (+ guard), Q15;
    # clamped below Nyquist
    g = []
    for n in range(129):
        f = min(440.0 * 2 ** ((n - 69) / 12), SR * 0.45)
        gg = math.tan(math.pi * f / SR)
        g.append(round(32767 * gg / (1 + gg)))
    t.append("/* one-pole (TPT) coefficient G = g/(1+g), g = tan(pi f/fs), f = MIDI note n's frequency; Q15 */")
    t.append(arr("TAB_ONEPOLE_G", "int16_t", g, 12))

    # constant-power pan, 0..127 (64 = centre): left and right gains, Q15
    pl, pr = [], []
    for p in range(128):
        a = (p / 127.0) * math.pi / 2
        pl.append(round(32767 * math.cos(a)))
        pr.append(round(32767 * math.sin(a)))
    t.append("/* constant-power pan, param 0..127: gains, Q15 */")
    t.append(arr("TAB_PAN_L", "int16_t", pl, 16))
    t.append(arr("TAB_PAN_R", "int16_t", pr, 16))

    # saturation: tanh over [-4, 4] in 256 steps (+ guard), Q15 output
    sat = [round(32767 * math.tanh(-4 + 8 * i / 256)) for i in range(257)]
    t.append("/* tanh over x in [-4, 4] (index (x + 4) * 32), Q15 */")
    t.append(arr("TAB_TANH", "int16_t", sat, 16))

    hdr = ["/* SPDX-License-Identifier: GPL-3.0-or-later",
           " * Generated by tools/gen_tables.py: do not edit. Integer tables for the audio path (no libm in core/). */",
           "#ifndef STK_TABLES_H", "#define STK_TABLES_H", "#include <stdint.h>", "",
           f"#define TAB_CTL {CTL}", ""]
    with open(out, "w") as f:
        f.write("\n".join(hdr) + "\n" + "\n\n".join(t) + "\n\n#endif\n")


if __name__ == "__main__":
    main(sys.argv[1])
